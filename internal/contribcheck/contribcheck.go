func decodeMetadata(b []byte) (metadataFile, error) {
	var m metadataFile
	dec := yaml.NewDecoder(bytes.NewReader(b))
	dec.KnownFields(true)
	if err := dec.Decode(&m); err != nil {
		return metadataFile{}, fmt.Errorf("decoding metadata.yaml into the keys contribcheck models: %w", err)
	}
	return m, nil
}

func metadataProblems(m metadataFile, want Expect) []string {
	var out []string
	add := func(format string, args ...any) {
		out = append(out, fmt.Sprintf(format, args...))
	}
	if m.Type != "bigquery" {
		add("type %q; want %q", m.Type, "bigquery")
	}
	if m.DisplayName == "" {
		add("display_name is empty")
	}
	if m.Status.Class != "exporter" {
		add("status.class %q; want %q", m.Status.Class, "exporter")
	}
	if msg := stabilityProblem(m.Status.Stability, want.Stability); msg != "" {
		add("%s", msg)
	}
	if got, exp := nonNil(m.Status.Distributions), nonNil(want.Distributions); !slices.Equal(got, exp) {
		add("status.distributions %v; want %v", got, exp)
	}
	out = append(out, codeownerProblems(m.Status.Codeowners.Active)...)
	switch q := m.SendingQueue; {
	case q == nil:
		add("sending_queue is not declared, but the component configuration has a sending_queue key")
	case q.Support != "default" && q.Support != "has_overrides":
		add("sending_queue.support %q; want default or has_overrides", q.Support)
	case q.Support == "has_overrides" && (q.Overrides == nil || q.Overrides.Enabled == nil ||
		q.Overrides.Batch == nil || q.Overrides.Batch.Enabled == nil):
		add("sending_queue.support is has_overrides, but overrides.enabled or overrides.batch.enabled is not set")
	}
	if m.Tests.SkipShutdown != want.SkipShutdown {
		add("tests.skip_shutdown %t; want %t", m.Tests.SkipShutdown, want.SkipShutdown)
	}
	for _, key := range []string{"project", "dataset"} {
		if s, _ := m.Tests.Config[key].(string); s == "" {
			add("tests.config.%s is not a non-empty string", key)
		}
	}
	if !slices.Contains(m.Tests.Goleak.Ignore.Top, opencensusWorker) {
		add("tests.goleak.ignore.top does not list %q", opencensusWorker)
	}
	return out
}

func stabilityProblem(stability map[string][]string, want string) string {
	if len(stability) != 1 {
		return fmt.Sprintf("status.stability declares %d levels; want only %s: [traces, logs, metrics]", len(stability), want)
	}
	for level, got := range stability {
		if level != want {
			return fmt.Sprintf("status.stability level %s; want %s", level, want)
		}
		if !slices.Equal(slices.Sorted(slices.Values(got)), signals) {
			return fmt.Sprintf("status.stability.%s lists %v; want traces, logs, and metrics once each", level, got)
		}
	}
	return ""
}

func codeownerProblems(active []string) []string {
	var out []string
	seen := make(map[string]bool)
	for _, h := range active {
		switch {
		case seen[h]:
			out = append(out, fmt.Sprintf("status.codeowners.active lists %q twice", h))
		case !isHandle(h) && !placeholderRE.MatchString(h):
			out = append(out, fmt.Sprintf("status.codeowners.active entry %q is neither a GitHub handle nor a <placeholder>", h))
		}
		seen[h] = true
	}
	if len(seen) < 3 {
		out = append(out, fmt.Sprintf("status.codeowners.active lists %d codeowners; want at least three", len(seen)))
	}
	return out
}

func isHandle(s string) bool {
	return len(s) <= 39 && handleRE.MatchString(s)
}

func nonNil(s []string) []string {
	if s == nil {
		return []string{}
	}
	return s
}

func mapKeys[V any](m map[string]V) func(yield func(string) bool) {
	return func(yield func(string) bool) {
		for k := range m {
			if !yield(k) {
				return
			}
		}
	}
}

// PendingCodeowners returns the placeholder entries of
// status.codeowners.active in a metadata.yaml, such as "<sponsor>", sorted.
// Each one stands for a handle that is not confirmed yet.
func PendingCodeowners(metadataYAML []byte) ([]string, error) {
	m, err := decodeMetadata(metadataYAML)
	if err != nil {
		return nil, err
	}
	var pending []string
	for _, h := range m.Status.Codeowners.Active {
		if placeholderRE.MatchString(h) {
			pending = append(pending, h)
		}
	}
	slices.Sort(pending)
	return pending, nil
}

// CheckPromotion checks that the metadata.yaml after the alpha promotion
// differs from the one before it only in two ways: all three signals move
// from development to alpha, and status.distributions becomes [contrib].
func CheckPromotion(before, after []byte) []Problem {
	const file = "metadata.yaml"
	b, err := decodeMetadata(before)
	if err != nil {
		return []Problem{{Check: "promotion", Path: file, Msg: "before: " + err.Error()}}
	}
	a, err := decodeMetadata(after)
	if err != nil {
		return []Problem{{Check: "promotion", Path: file, Msg: "after: " + err.Error()}}
	}
	var problems []Problem
	report := func(format string, args ...any) {
		problems = append(problems, Problem{Check: "promotion", Path: file, Msg: fmt.Sprintf(format, args...)})
	}
	if msg := stabilityProblem(b.Status.Stability, "development"); msg != "" {
		report("before: %s", msg)
	}
	if msg := stabilityProblem(a.Status.Stability, "alpha"); msg != "" {
		report("after: %s", msg)
	}
	if len(b.Status.Distributions) != 0 {
		report("before: status.distributions %v; want []", b.Status.Distributions)
	}
	if !slices.Equal(a.Status.Distributions, []string{"contrib"}) {
		report("after: status.distributions %v; want [contrib]", a.Status.Distributions)
	}
	b.Status.Stability, a.Status.Stability = nil, nil
	b.Status.Distributions, a.Status.Distributions = nil, nil
	if !reflect.DeepEqual(a, b) {
		report("changes keys other than status.stability and status.distributions")
	}
	sortProblems(problems)
	return problems
}

// Status says how far contribcheck can establish a contrib make gate.
type Status string

const (
	// StaticPrecondition marks a gate whose preconditions CheckTree checks
	// on a staged tree. The gate itself still has to run in a checkout.
	StaticPrecondition Status = "static precondition verified locally"
	// NeedsCheckout marks a gate that reads or writes files outside the
	// component directory, so nothing about it can be checked here.
	NeedsCheckout Status = "requires upstream checkout"
)

// Gate is one contrib make target that a donation pull request runs.
type Gate struct {
	// Target is the make target.
	Target string
	// Source is the file and line of Recipe at PinnedCommit.
	Source string
	// Recipe is a verbatim excerpt of the target's recipe at Source.
	Recipe string
	// Status says how far contribcheck can establish the gate.
	Status Status
	// InIssue reports whether the gate is one of the fifteen listed in
	// item 5.6 of the v0.1.0 milestone issue. The others come from the
	// first-PR checklist of docs/new-components.md at PinnedCommit.
	InIssue bool
}

