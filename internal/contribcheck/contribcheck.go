// Package contribcheck checks the drafts in docs/upstream that stage the
// donation of this exporter to opentelemetry-collector-contrib.
//
// The drafts carry every file of each staged contrib pull request as a fenced
// code block directly below a marker line:
//
//	<!-- contribcheck:file pr=1 path=exporter/bigqueryexporter/doc.go -->
//
// Extract reads those blocks, Tree overlays them into the component directory
// that a pull request leaves behind, and CheckTree applies static checks to
// such a directory. The checks are preconditions of the contrib make gates
// that Gates lists; they do not run those gates. A precondition that holds
// here is not a gate that passed in an upstream checkout.
